import { chromium } from 'playwright-core';
import { readdirSync, existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
const exe = (() => { const b = '/opt/pw-browsers'; for (const d of readdirSync(b).filter((x) => x.startsWith('chromium-')).sort().reverse()) { const p = path.join(b, d, 'chrome-linux', 'chrome'); if (existsSync(p)) return p; } })();
const browser = await chromium.launch({ executablePath: exe, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ acceptDownloads: true, viewport: { width: 1440, height: 900 } });
await ctx.addInitScript(() => { sessionStorage.setItem('opt.auth', JSON.stringify({ email: 'coo@optimo.com.sa', name: 'coo', role: 'coo' })); localStorage.setItem('opt.machineLibrary.selected', 'treadmill'); });
const page = await ctx.newPage();
const reqs = [];
page.on('request', (r) => { if (!r.url().startsWith('http://localhost') && !r.url().startsWith('data:') && !r.url().startsWith('blob:')) reqs.push(r.url()); });
await page.goto('http://localhost:5206/#/machine-library');
await page.waitForTimeout(4000);
page.on('console', (m) => console.log('console', m.type(), m.text())); page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.waitForTimeout(500);
const [dl] = await Promise.all([page.waitForEvent('download', { timeout: 20000 }).catch(async (e) => { console.log('msg:', await page.locator('.ml-msg').textContent().catch(() => '-')); throw e; }), page.locator('.ml-download').click()]);
const p = await dl.path();
const buf = readFileSync(p);
console.log('file', dl.suggestedFilename(), buf.length, 'bytes, magic', buf.subarray(0, 4).toString(), 'version', buf.readUInt32LE(4));
const jsonLen = buf.readUInt32LE(12); const json = JSON.parse(buf.subarray(20, 20 + jsonLen).toString());
console.log('meshes', json.meshes.length, 'materials', json.materials.map((m) => m.name).join(','), 'nodes', json.nodes.length);
console.log('status:', await page.locator('.ml-msg').textContent());
console.log('external requests:', reqs.length ? reqs : 'none');
await browser.close();
